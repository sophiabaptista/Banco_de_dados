SELECT * FROM CLIENTES;
SELECT * FROM VEICULOS;
SELECT * FROM AGENDAMENTOS;

SELECT
    C.NOME,
    COUNT(V.ID) AS QUANTIDADE_CARROS
FROM CLIENTES C
LEFT JOIN VEICULOS V
ON C.ID = V.FK_CLI_ID
GROUP BY C.ID, C.NOME;

SELECT
    V.MODELO,
    COUNT(A.ID) AS QUANTIDADE_AGENDAMENTOS
FROM VEICULOS V
LEFT JOIN AGENDAMENTOS A
ON V.ID = A.VEICULO_ID
GROUP BY V.ID, V.MODELO;

SELECT
    C.NOME AS 'NOME DO CLIENTE',
    COUNT(A.ID) AS 'QUANTIDADE DE AGENDAMENTOS'
FROM CLIENTES C
LEFT JOIN VEICULOS V
ON C.ID = V.FK_CLI_ID
LEFT JOIN AGENDAMENTOS A
ON V.ID = A.VEICULO_ID
GROUP BY C.ID, C.NOME;
